const CSV_KEYS = new Set<string>(CSV_COLUMN_GROUPS.map((g) => g.key));
const PDF_KEYS = new Set<string>(PDF_SECTIONS.map((s) => s.key));

function parseList<K extends string>(raw: string | null, allowed: Set<string>): K[] | null {
  if (raw === null) return null;
  const keys = [...new Set(raw.split(",").map((s) => s.trim()).filter((s) => allowed.has(s)))];
  return keys as K[];
}

/** `null` = param absent (export everything, the original behavior); `[]` = nothing valid was chosen. */
export function parseCsvColumnGroups(raw: string | null): CsvColumnGroupKey[] | null {
  return parseList<CsvColumnGroupKey>(raw, CSV_KEYS);
}

export function parsePdfSections(raw: string | null): PdfSectionKey[] | null {
  return parseList<PdfSectionKey>(raw, PDF_KEYS);
}

/** Headers to keep for the chosen groups; null = all. */
export function headersForGroups(groups: CsvColumnGroupKey[] | null): Set<string> | null {
  if (!groups) return null;
  return new Set(CSV_COLUMN_GROUPS.filter((g) => groups.includes(g.key)).flatMap((g) => [...g.headers]));
}
